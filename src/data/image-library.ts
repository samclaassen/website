const BY_ID = new Map(IMAGE_LIBRARY.map((img) => [img.id, img]));

export function libraryImage(id: string): LibraryImage {
  const img = BY_ID.get(id);
  if (!img) throw new Error(`Unknown library image: ${id}`);
  return img;
}

/** A library image in the shape CreditedImage expects. */
export function libraryPhoto(id: string): CreditedPhoto {
  const img = libraryImage(id);
  return {
    src: img.file,
    alt: img.alt,
    credit: img.credit,
    sourceUrl: img.sourceUrl,
    rightsBasis: img.rightsBasis,
    license: img.license,
    licenseUrl: img.licenseUrl,
    dateCleared: img.checkedAt,
    width: img.width,
    height: img.height,
    focus: img.focus,
  };
}
